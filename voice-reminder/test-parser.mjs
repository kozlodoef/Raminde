import { parseReminder } from './src/lib/timeParser.js';

// ВАЖНО про точность: `fmt` выводит минуты без секунд, а относительные фразы
// отсчитываются от «сейчас» в момент разбора. Поэтому для таких случаев задан
// допуск в минутах — иначе тест ловил бы переход через границу минуты.
const now = new Date();
const p = (n) => String(n).padStart(2, '0');
const fmt = (d) => `${d.getFullYear()}-${p(d.getMonth()+1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`;
const addDays = (d, n) => { const x = new Date(d); x.setDate(x.getDate() + n); return x; };
const at = (dayShift, h, m = 0) => { const d = addDays(now, dayShift); d.setHours(h, m, 0, 0); return fmt(d); };
const inMin = (n) => fmt(new Date(now.getTime() + n * 60e3));
const atClock = (h, m = 0) => { const d = new Date(now); d.setHours(h, m, 0, 0); if (d <= now) d.setDate(d.getDate() + 1); return fmt(d); };
const TOL = 2;   // допуск для относительных фраз, в минутах

// [фраза, ожидаемое "когда" (null — зависит от текущего времени), ожидаемый текст действия, допуск в минутах]
const cases = [
  // --- базовые случаи (были в первой версии теста) ---
  ['Напомни мне завтра в семь утра полить цветы', at(1, 7), 'Полить цветы', 1],
  ['Напомнить через два часа позвонить маме', inMin(120), 'Позвонить маме', TOL],
  ['напомни 15 октября в 10 утра сдать отчёт', at(0, 0).slice(0,4) + '-10-15 10:00', 'Сдать отчет', 1],
  ['напомни сегодня без четверти шесть забрать ребёнка из школы', null, 'Забрать ребенка из школы'],
  ['Напомни завтра в половине десятого позвонить врачу', at(1, 9, 30), 'Позвонить врачу', 1],
  ['напомни через полчаса выпить таблетки', inMin(30), 'Выпить таблетки', TOL],
  ['Напомни послезавтра в 3 дня встречу с директором', at(2, 15), 'Встречу с директором', 1],
  ['Напомни в десять вечера позвонить бабушке', atClock(22), 'Позвонить бабушке', 1],
  ['Напомни в 15:30 созвониться с командой', atClock(15, 30), 'Созвониться с командой', 1],
  ['Напомни полшестого вечером покормить кота', atClock(17, 30), 'Покормить кота', 1],
  ['Напомни в пятницу утром стирку', null, 'Стирку'],

  // --- относительные: единица без числа (раньше не работало) ---
  ['Напомни через час позвонить', inMin(60), 'Позвонить', TOL],
  ['Напомни через минуту выключить', inMin(1), 'Выключить', TOL],
  ['Напомни через неделю сдать отчёт', inMin(7 * 1440), 'Сдать отчет', TOL],
  ['Напомни через месяц продлить подписку', null, 'Продлить подписку'],

  // --- относительные: круглые десятки (раньше не работало) ---
  ['Напомни через тридцать минут проверить', inMin(30), 'Проверить', TOL],
  ['Напомни через двадцать минут выйти', inMin(20), 'Выйти', TOL],
  ['Напомни через сорок минут обед', inMin(40), 'Обед', TOL],

  // --- относительные: составные числа (раньше не работало) ---
  ['Напомни через двадцать пять минут', inMin(25), 'Напоминание', TOL],
  ['Напомни через тридцать пять минут', inMin(35), 'Напоминание', TOL],
  ['Напомни через сорок пять минут', inMin(45), 'Напоминание', TOL],

  // --- относительные: прочие формы ---
  ['Напомни через две минуты', inMin(2), 'Напоминание', TOL],
  ['Напомни через 45 минут', inMin(45), 'Напоминание', TOL],
  ['Напомни через полтора часа', inMin(90), 'Напоминание', TOL],
  ['Напомни через три дня встречу', inMin(3 * 1440), 'Встречу', TOL],

  // --- части суток без явного часа ---
  ['Напомни завтра утром зарядка', at(1, 9), 'Зарядка', 1],
  ['Напомни завтра днем обед', at(1, 15), 'Обед', 1],
  ['Напомни завтра вечером кино', at(1, 19), 'Кино', 1],
  ['Напомни в пятницу вечером гости', null, 'Гости'],

  // --- абсолютные даты ---
  ['Напомни 25 декабря купить подарки', null, 'Купить подарки'],
  ['Напомни 25 декабря 2026 в 12:00', '2026-12-25 12:00', 'Напоминание', 1],
  ['Напомни 3 января в 10 утра', null, 'Напоминание'],
  ['Напомни 1 сентября в 8:30 линейка', null, 'Линейка'],

  // --- время ---
  ['Напомни в 10:05 позвонить', null, 'Позвонить'],
  ['Напомни в 23:59 выключить', atClock(23, 59), 'Выключить', 1],
  ['Напомни в 7 вечера', atClock(19), 'Напоминание', 1],
  ['Напомни в полдень обед', atClock(12), 'Обед', 1],
  ['Напомни в полночь', null, 'Напоминание'],
  ['Напомни в 5 часов вечера', atClock(17), 'Напоминание', 1],
  ['Напомни в понедельник утром планёрка', null, 'Планерка'],
  ['Напомни в воскресенье в 12:00', null, 'Напоминание'],

  // --- без времени и даты ---
  ['Напомни позвонить маме', null, 'Позвонить маме'],
];

let pass = 0, fail = 0;
for (const [phrase, expectWhen, expectText, tolMin] of cases) {
  const r = parseReminder(phrase);
  const got = fmt(r.when);
  let okTime;
  if (expectWhen === null) {
    okTime = true;                                   // зависит от текущего времени
  } else if (tolMin) {
    okTime = Math.abs(r.when.getTime() - new Date(expectWhen).getTime()) <= tolMin * 60e3;
  } else {
    okTime = got === expectWhen;
  }
  const okText = r.text.toLowerCase().includes(expectText.toLowerCase().slice(0, 8));
  if (okTime && okText) { pass++; console.log(`✅ "${phrase}"\n     → ${got} | "${r.text}"`); }
  else { fail++; console.log(`❌ "${phrase}"\n     → ${got} | "${r.text}" (ожидалось ${expectWhen || '—'} | ${expectText})`); }
}
console.log(`\nПройдено: ${pass}, Провалено: ${fail}`);
process.exit(fail ? 1 : 0);
