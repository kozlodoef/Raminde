// lib/flip-time.js — логика перекидных цифр времени.
//
// Вынесено из компонента, чтобы ограничения (час ≤ 23, минута ≤ 59) и
// переходы можно было проверять тестами. Компонент только рисует карточки
// и играет звук, решения о цифрах принимает этот модуль.
//
// Часы считаются парой (0–23), минуты парой (0–59). Тогда шаг вперёд от
// 23:00 даёт 00:00, а не 20:00 — как ожидает человек, а оборот «на месте»
// не рвёт соседнюю цифру.

/** Разбирает "чч:мм" в четыре цифры: [десятки ч, единицы ч, десятки м, единицы м]. */
export function parseTimeDigits(value) {
  const m = String(value || "00:00").match(/(\d{1,2}):(\d{1,2})/);
  const hh = (m ? m[1] : "0").padStart(2, "0");
  const mm = (m ? m[2] : "0").padStart(2, "0");
  return [Number(hh[0]), Number(hh[1]), Number(mm[0]), Number(mm[1])];
}

/** Собирает строку "чч:мм" из четырёх цифр. */
export function formatTimeDigits(digits) {
  return `${digits[0]}${digits[1]}:${digits[2]}${digits[3]}`;
}

/**
 * Сдвигает одну цифру на шаг.
 *
 * Часы и минуты считаются как пары: сдвиг цифры меняет весь час (0–23) или
 * всю минуту (0–59) с оборотом. Возвращает новый массив; исходный не
 * меняется, чтобы React мог сравнивать состояния.
 */
export function stepTimeDigit(digits, i, dir) {
  const nd = [...digits];
  if (i <= 1) {
    // Часы как пара 0–23. Десятки сдвигает на 10, единицы — на 1.
    let hour = digits[0] * 10 + digits[1];
    hour += dir * (i === 0 ? 10 : 1);
    hour = ((hour % 24) + 24) % 24;
    nd[0] = Math.floor(hour / 10);
    nd[1] = hour % 10;
  } else {
    // Минуты как пара 0–59.
    let minute = digits[2] * 10 + digits[3];
    minute += dir * (i === 2 ? 10 : 1);
    minute = ((minute % 60) + 60) % 60;
    nd[2] = Math.floor(minute / 10);
    nd[3] = minute % 10;
  }
  return nd;
}
