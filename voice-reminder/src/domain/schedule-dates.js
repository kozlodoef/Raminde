// domain/schedule-dates.js — на какие дни рассчитано напоминание.
//
// Нужно, чтобы отличить «одно событие» от «серии»: удаляя карточку одного
// дня, человек должен знать, исчезнет ли только этот день или вся серия.
// Считать по датам расписания проще и надёжнее, чем по всем срабатываниям:
// у повторяющегося правила их бесконечно много, а решение зависит именно от
// того, сколько разных дат в расписании.

import { localDate } from "./calendar.js";

/**
 * Даты, на которые расписано правило.
 *
 * Для правила на конкретные даты возвращает их список. Для ежедневного или
 * еженедельного — пустой массив: там дат «по списку» нет, и удалять одну
 * дату бессмысленно — правильнее считать такое правило одним событием,
 * которое повторяется.
 */
export function ruleDates(rule) {
  const s = rule?.schedule;
  if (!s) return [];
  if (s.kind === "dates") return [...new Set(s.dates || [])].sort();
  if (s.kind === "once") return s.at ? [localDate(new Date(s.at))] : [];
  return [];
}

/** Стоит ли правило больше чем на один день. */
export function spansSeveralDays(rule) {
  return ruleDates(rule).length > 1;
}

/**
 * Сколько всего срабатываний даёт правило.
 *
 * Считаем даты, умноженные на времена: «26 ноября в 9:00 и в 12:00» — это два
 * события, хотя дата одна. Без этого удаление карточки одного времени уносило
 * бы и второе, а человек об этом не просил.
 *
 * Для повторов возвращаем 0: у них нет конечного списка, и вопрос «только это
 * или все» к ним не подходит.
 */
export function ruleOccurrenceCount(rule) {
  const s = rule?.schedule;
  if (!s) return 0;
  if (s.kind === "once") return s.at ? 1 : 0;
  if (s.kind !== "dates") return 0;
  const dates = ruleDates(rule).length;
  const times = Math.max(1, (s.times || []).length);
  return dates * times;
}
