// A calendar month from first activation, never reset at the start of a month.
export function addMonth(timestamp) {
  const d = new Date(timestamp),
    day = d.getUTCDate();
  d.setUTCDate(1);
  d.setUTCMonth(d.getUTCMonth() + 1);
  d.setUTCDate(
    Math.min(
      day,
      new Date(
        Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + 1, 0),
      ).getUTCDate(),
    ),
  );
  return d.getTime();
}
export function trialAccess(existing, now = Date.now()) {
  const start = Number.isFinite(existing?.trialStartedAt)
    ? existing.trialStartedAt
    : now;
  return { ...existing, trialStartedAt: start, trialEndsAt: addMonth(start) };
}
/**
 * Идёт ли оплаченный период.
 *
 * Раньше здесь был единственный признак «всё можно»: пока месяц не кончился,
 * доступно всё, после — ничего. Такой стены больше нет: напоминания работают
 * всегда, а подписка снимает дневной предел в три напоминания.
 */
export function accessActive(access, now = Date.now()) {
  return (access?.trialEndsAt || 0) > now || (access?.paidUntil || 0) > now;
}
/**
 * Распознавание дат из речи.
 *
 * Раньше это была возможность платной версии: голосом задавались только время
 * и событие, а даты человек отмечал на календаре. На практике вышло хуже:
 * «двадцать пятого декабря» уходило в текст, и напоминание срабатывало
 * сегодня. Дата из речи — обычное ожидание, а не роскошь, поэтому сейчас она
 * доступна всем. Функция оставлена, чтобы вызовы не менялись, если ограничение
 * понадобится вернуть.
 */
export function dateSpeechEnabled() {
  return true;
}

/** Сколько дат можно отметить на одно событие. Сейчас без ограничений. */
export const MAX_DATES_PER_EVENT = null;
/**
 * Предел напоминаний на один день без подписки.
 *
 * Три напоминания в день — это и есть ограничение бесплатной версии. Стена
 * «пробный месяц закончился, покупайте» снята: она делала приложение
 * неработоспособным на тридцать первый день, а кнопка оплаты в тестовой
 * сборке никуда не вела. Предел мягкий: уже созданные напоминания не
 * отключаются, ограничивается только создание новых.
 *
 * Место в дне занимают и запланированные напоминания: иначе предел не
 * ограничивал бы планирование вовсе. Но напоминание, убранное ДО
 * срабатывания, место освобождает — оно ничего не потратило. Прозвучавшее
 * место сохраняет даже после удаления: иначе предел обходится в два нажатия
 * «поставить — дождаться — удалить». Подробности в day-capacity.js.
 */
export const FREE_REMINDERS_PER_DAY = 3;

/**
 * Технический предел напоминаний на один день.
 *
 * В сутках 24 часа, больше 24 отдельных напоминаний поставить нельзя.
 * Раньше здесь стояло 12, и это упиралось в обычный плотный день. При
 * активной подписке остаётся только эта граница.
 */
export const MAX_REMINDERS_PER_DAY = 24;

/**
 * Предел напоминаний в день для текущего состояния.
 *
 * Веб-версия без настроенного эквайринга подписку проверить не может,
 * поэтому там действует тот же предел в три напоминания: иначе весь смысл
 * ограничения теряется, стоит открыть предпросмотр в браузере.
 */
export function dailyLimit(bill) {
  return isPro(bill) ? MAX_REMINDERS_PER_DAY : FREE_REMINDERS_PER_DAY;
}

/**
 * Признак подписки.
 *
 * Подписка не открывает новые функции — она снимает дневной предел.
 * Функция остаётся единственной точкой, где этот признак читается.
 */
export function isPro(bill) {
  return !!bill?.premium;
}

