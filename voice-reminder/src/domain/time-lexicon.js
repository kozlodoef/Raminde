// domain/time-lexicon.js — единственный источник правды о том, как в русском
// языке называют время.
//
// Зачем отдельный модуль. Логика времени была размазана по трём файлам
// (lib/timeParser.js, domain/groups.js, domain/phrase-digits.js), и каждый раз
// её латали по отдельности. Один и тот же оборот понимался по-разному:
// «10:00 тридцать» работало, а «10:00 30» — нет; «10 30» без двоеточия не
// понималось вовсе; «10.30» не считалось временем. Ошибка возвращалась после
// каждой заплатки, потому что правка попадала в один слой из трёх.
//
// Здесь собраны ВСЕ формы, которые приложение обязано понимать, и разбор
// каждой из них. Каталог TIME_FORMS проверяется тестом: каждая запись
// прогоняется через три реальных пути разбора и должна дать одно время.
// Добавляя форму — сначала добавьте её в каталог, потом в разбор.
//
// Границы слов задаём просмотром, а не \b: в JavaScript \b не считает
// кириллицу буквами, и «вечера» им не ловится.

