/** Части суток: поправка к часу («в десять вечера» → 22:00). */
export const PARTS_OF_DAY = {
  утра: "morning", утром: "morning",
  дня: "afternoon", днём: "afternoon", днем: "afternoon",
  вечера: "evening", вечером: "evening",
  ночи: "night", ночью: "night",
};

/** Названия частей суток, сказанные вместо часа: «в обед». */
export const DAYPARTS = { обед: "13:00", полдень: "12:00", полночь: "00:00" };

/**
 * «Обед» — слово двусмысленное: это и время (около 13:00), и еда.
 *
 * Время берём только при явном предлоге времени («в обед») и только если
 * рядом не названа другая часть суток: «завтра днём обед» — это напоминание
 * поесть в 15:00, а не «в 13:00». Иначе «обед» съедался как время, и текст
 * напоминания оставался пустым.
 */
export function daypartClock(text, neighbours = "") {
  const v = norm(text);
  if (v === "полдень" || v === "полудня") return "12:00";
  if (v === "полночь" || v === "полуночи") return "00:00";
  if (v !== "обед") return null;
  if (daypartIn(neighbours)) return null;
  return "13:00";
}

/** Основы названий месяцев — чтобы отличить дату от минут («25 мая»). */
export const MONTH_WORDS = [
  "январ", "феврал", "март", "апрел", "ма[йя]", "мае", "маю", "июн",
  "июл", "август", "сентябр", "октябр", "ноябр", "декабр",
];

const norm = (s) => String(s).toLowerCase().replaceAll("ё", "е").trim();
const pad = (n) => String(n).padStart(2, "0");
const LB = "(?<!\\p{L})";
const RB = "(?!\\p{L})";
const stripWord = (re) => new RegExp(LB + "(?:" + re + ")" + RB, "gu");

const DAYPART_RE = /утра|утром|вечера|вечером|дня|днём|днем|ночи|ночью/u;
const HOURS_WORD_RE = stripWord("час(?:а|ов)?");
const MINUTES_WORD_RE = stripWord("минут(?:а|ы|у)?");

const clock = (hour, minute) =>
  typeof hour === "number" && typeof minute === "number" &&
  Number.isFinite(hour) && Number.isFinite(minute) &&
  hour >= 0 && hour <= 23 && minute >= 0 && minute <= 59
    ? { hour, minute }
    : null;

/** Значение времени как «ЧЧ:ММ». */
export function formatClock(hour, minute) {
  const c = clock(hour, minute);
  return c ? pad(c.hour) + ":" + pad(c.minute) : null;
}

/** Число из слова или цифр: «пять» → 5, «двадцать пять» → 25, «30» → 30. */
export function numFromText(text) {
  const k = norm(text);
  if (!k) return null;
  if (/^\d+$/.test(k)) return Number(k);
  const parts = k.split(/[\s-]+/).filter(Boolean);
  let total = 0;
  let seen = false;
  for (const p of parts) {
    if (TENS[p] !== undefined) total += TENS[p];
    else if (NUM_WORDS[p] !== undefined) total += NUM_WORDS[p];
    else if (NUM_WORDS_GENITIVE[p] !== undefined) total += NUM_WORDS_GENITIVE[p];
    else return null;
    seen = true;
  }
  return seen ? total : null;
}

/** Минуты словами или цифрами: «тридцать» → 30, «двадцать пять» → 25. */
export function minutesFromText(text) {
  const v = numFromText(text);
  return v === null || v > 59 ? null : v;
}

/** Поправка часа по части суток: «в десять вечера» → 22. */
export function applyDaypart(hour, part) {
  const kind = typeof part === "string" && PARTS_OF_DAY[part]
    ? PARTS_OF_DAY[part]
    : part;
  let h = hour;
  if ((kind === "evening" || kind === "afternoon") && h < 12) h += 12;
  if (kind === "night" && h === 12) h = 0;
  return h;
}

/** Название части суток в тексте: «вечера» → evening. */
export function daypartIn(text) {
  const m = String(text || "").toLowerCase().match(DAYPART_RE);
  return m ? PARTS_OF_DAY[m[0]] : null;
}

/** Первое слово текста — нужно, чтобы понять, что идёт следом. */
export function firstWord(text) {
  const m = String(text || "").match(/^\s*([а-яёА-ЯЁa-zA-Z-]+)/u);
  return m ? m[1] : null;
}

/** Название месяца целиком: «мая» — да, «мартышку» — нет. */
export function isMonthWord(word) {
  if (!word) return false;
  const w = norm(word);
  return MONTH_WORDS.some((m) => new RegExp("^(?:" + m + ")$", "u").test(w));
}

/**
 * Принимать ли минуты, стоящие отдельным словом после часа.
 *
 * Минуты — это уточнение времени, и оно звучит в конце фразы, перед словом
 * «минут» или перед глаголом действия: «в 16:00 тридцать», «16:00 тридцать
 * минут», «16:00 тридцать позвонить». За количеством идёт существительное:
 * «в 8 два хлеба», «16:00 тридцать человек придут» — это не минуты.
 *
 * @param {string} clockPart — запись времени с минутами («16:00 тридцать»)
 * @param {string} whole — вся фраза, чтобы увидеть следующее слово
 */
export function minutesAccepted(clockPart, whole) {
  if (!whole) return true;
  const at = whole.indexOf(clockPart);
  if (at < 0) return true;
  const next = firstWord(whole.slice(at + clockPart.length));
  if (!next) return true;
  if (/^минут/u.test(next)) return true;
  return VERB_AFTER.test(next);
}

/**
 * Считается ли запись «час + отдельные минуты» именно временем.
 *
 * Общее правило для всех путей: минуты-слова принимаются, когда за ними
 * конец фразы, «минут» или глагол действия. За количеством идёт
 * существительное: «16:00 тридцать человек придут» — это 16:00 и тридцать
 * человек, а не 16:30.
 */
export function separateMinutesAccepted(clockPart, whole) {
  return minutesAccepted(clockPart, whole);
}

/** Минуты-слова принимаются в конце фразы или перед глаголом действия. */
export const VERB_AFTER = /(?:[а-яёы]ть|сти)$/;

/**
 * Запись времени, которую можно признать временем без предлога «в».
 *
 * Голое число («2», «10») временем не считается: «купить 2 хлеба» — это
 * количество. Признаком времени служит двоеточие, точка, слово «час»/«минут»,
 * «без», «половина», «четверть», порядковое число часа или часть суток.
 */
export const STRONG_TIME =
  /(?::|\.\s*\d|час|минут|без\s|пол|четверт|полдень|полноч|обед|утра|вечера|дня|ночи|надцат|дцать|сорок|пятьдесят|одиннадцатого|десятого)/u;

/** Есть ли в записи признак времени, кроме голого числа. */
export function looksLikeTime(text) {
  return STRONG_TIME.test(String(text || ""));
}

// Десяток в родительном падеже с единицей — «двадцати пяти». Обычные числительные
// в этом падеже не совпадают с именительными, поэтому нужен отдельный шаблон.
const TENS_GEN = {
  двадцати: 20, тридцати: 30, сорока: 40, пятидесяти: 50,
};
const UNIT_GEN =
  "одной|двух|трёх|трех|четырёх|четырех|пяти|шести|семи|восьми|девяти";
const TENS_GEN_SRC =
  "(?:" + Object.keys(TENS_GEN).join("|") + ")" +
  "(?:[-\\s]+(?:" + UNIT_GEN + "))?";

// «час»/«минуты» отдельными шаблонами: их надо снять до числового разбора.
const ALT_NUM = "\\d{1,2}|[а-яё-]+(?:\\s+[а-яё-]+)?";
const RE_BEZ = new RegExp(
  "^без\\s+(четверти|половины|" + TENS_GEN_SRC + "|[а-яё-]+|\\d{1,2})(?:\\s+минут[а-яё]*)?\\s+([а-яё-]+|\\d{1,2})$",
  "u",
);
const RE_MIN_ORDINAL = new RegExp(
  "^(" + ALT_NUM + ")\\s+минут[а-яё]*\\s+([а-яё-]+)$",
  "u",
);
const RE_HALF_ORDINAL = new RegExp(
  "^половин[а-яё]*\\s+([а-яё-]+)$|^пол[-\\s]?([а-яё-]+)$",
  "u",
);
const RE_QUARTER_ORDINAL = new RegExp(
  "^четверть\\s+([а-яё-]+)$",
  "u",
);
const RE_QUARTER_AFTER = new RegExp(
  "^(" + ALT_NUM + ")\\s+с\\s+четвертью$",
  "u",
);

/**
 * Разбирает одну «порцию» времени — то, что уже вырезано из фразы.
 *
 * Понимает все формы из каталога TIME_FORMS: цифры с двоеточием, точкой и
 * пробелом, слова, смешанные записи, «часов»/«минут», дроби (половина,
 * четверть), «без N …», «N минут <порядковое>», части суток.
 *
 * @returns {{hour:number, minute:number}|null}
 */
export function parseClockText(raw, neighbours = "") {
  let v = norm(raw);
  if (!v) return null;
  // Особые названия времени суток вместо часа. «Обед» учитывает соседей:
  // рядом с «днём»/«вечером» это еда, а не время.
  if (DAYPARTS[v]) {
    const clockText = daypartClock(v, neighbours);
    if (!clockText) return null;
    const [h, m] = clockText.split(":").map(Number);
    return { hour: h, minute: m };
  }
  // Часть суток запоминаем и снимаем: «десять вечера» → час 10 + вечер.
  const part = daypartIn(v);
  v = v.replace(DAYPART_RE, " ");
  // «без четверти шесть», «без пятнадцати три», «без половины шесть».
  const bez = v.replace(/\s+/g, " ").trim().match(RE_BEZ);
  if (bez) {
    // «четверть» — 15, «половина» — 30, иначе число словами. Составное число
    // («двадцати пяти») складывается из десятка и единицы.
    const sub = /^четвер/u.test(bez[1])
      ? 15
      : /^половин/u.test(bez[1])
        ? 30
        : numFromText(bez[1]);
    // Час после «без» часто называют порядковым числительным: «без пятнадцати
    // шестого» — то же, что «без пятнадцати шесть». «Шестого» называет час,
    // к которому относятся минуты, поэтому считается так же, как «шесть».
    // Без этой ветки «шестого» не опознавалось как число, разбор возвращал
    // null, и время ловилось по обрывку «пятнадцати» — получалось 15:00.
    const baseOrd = ORDINALS[norm(bez[2])];
    const base = baseOrd !== undefined ? baseOrd : numFromText(bez[2]);
    if (sub !== null && sub < 60 && base !== null) {
      let hour = base - 1;
      let minute = 60 - sub;
      if (minute >= 60) { minute = 0; hour += 1; }
      if (hour < 0) hour += 24;
      return clock(applyDaypart(hour, part), minute);
    }
    return null;
  }
  // «тридцать минут одиннадцатого» — минуты плюс порядковое число часа.
  const mo = v.replace(/\s+/g, " ").trim().match(RE_MIN_ORDINAL);
  if (mo && ORDINALS[norm(mo[2])] !== undefined) {
    const minute = minutesFromText(mo[1]);
    const hour = ORDINALS[norm(mo[2])] - 1;
    if (minute !== null) return clock(applyDaypart(hour, part), minute);
    return null;
  }
  // «половина одиннадцатого», «пол-одиннадцатого», «полдевятого» — 30 минут.
  const ho = v.replace(/\s+/g, " ").trim().match(RE_HALF_ORDINAL);
  if (ho) {
    const key = norm(ho[1] || ho[2] || "");
    if (ORDINALS[key] !== undefined) {
      const hour = ORDINALS[key] - 1;
      return clock(applyDaypart(hour, part), 30);
    }
  }
  // «четверть одиннадцатого» — 15 минут.
  const qo = v.replace(/\s+/g, " ").trim().match(RE_QUARTER_ORDINAL);
  if (qo && ORDINALS[norm(qo[1])] !== undefined) {
    const hour = ORDINALS[norm(qo[1])] - 1;
    return clock(applyDaypart(hour, part), 15);
  }
  // «шесть с четвертью».
  const qa = v.replace(/\s+/g, " ").trim().match(RE_QUARTER_AFTER);
  if (qa) {
    const hour = numFromText(qa[1]);
    if (hour !== null) return clock(applyDaypart(hour, part), 15);
  }
  // Дальше — обычные записи. Снимаем служебные слова «часов» и «минут».
  v = v.replace(HOURS_WORD_RE, " ").replace(MINUTES_WORD_RE, " ");
  v = v.replace(/\s+/g, " ").trim();
  if (!v) return null;
  const done = (c) => (c ? clock(applyDaypart(c.hour, part), c.minute) : null);

  // Цифры с двоеточием: «10:30», «9:5», «10:30:00» (секунды не часть времени).
  let m = v.match(/^(\d{1,2}):(\d{1,2})(?::\d{1,2})?$/u);
  if (m) return done(clock(Number(m[1]), Number(m[2])));
  // Двоеточие плюс отдельные минуты: «16:00 тридцать», «10:00 30»,
  // «17:00 двадцать пять». Минуты могут быть двумя словами.
  m = v.match(/^(\d{1,2}):(\d{1,2})\s+(.+)$/u);
  if (m && Number(m[2]) === 0) {
    const rest = m[3].replace(/\s+минут[а-яё]*$/u, "");
    const minute = minutesFromText(rest);
    // Минуты берём, только если за ними конец фразы, «минут» или глагол
    // действия. За количеством идёт существительное («16:00 тридцать
    // человек придут») — тогда это не минуты, и слово остаётся в тексте.
    if (minute !== null && minutesAccepted(m[0], neighbours)) {
      return done(clock(Number(m[1]), minute));
    }
  }
  // Точка вместо двоеточия: «10.30». Вторая часть должна быть больше 12,
  // иначе это дата («15.10»), а не время.
  m = v.match(/^(\d{1,2})\.(\d{1,2})$/u);
  if (m) {
    const minute = Number(m[2]);
    return minute > 12 ? done(clock(Number(m[1]), minute)) : null;
  }
  // Два числа подряд — распознаватель убрал двоеточие: «10 30».
  m = v.match(/^(\d{1,2})\s+(\d{1,2})$/u);
  if (m) {
    const hour = Number(m[1]);
    const minute = Number(m[2]);
    // Второе число больше 12 — точно минуты. Меньшее принимаем только при
    // часе больше 12: «22 05» — время, «10 05» может быть датой.
    if (minute > 12 || hour > 12) return done(clock(hour, minute));
    return null;
  }
  // Число-час перед названием месяца — это дата («16 мая», «16 25 мая»),
  // а не время. Проверка здесь, а не только в шаблоне поиска: разбор
  // вызывают и напрямую, и по куску фразы.
  if (/^(?:\d{1,2}|[а-яё-]+)$/u.test(v) && isMonthWord(v)) return null;
  // Число и слово минут: «10 тридцать», «16 двадцать пять».
  // Одиночное слово-единица («8 два») минутами НЕ считается: за ним обычно
  // стоит существительное-количество — «в 8 два хлеба купить» это 08:00, а
  // не 08:02. Минуты из единиц пишут через «ноль» («девять ноль пять»).
  m = v.match(/^(\d{1,2})\s+([а-яё-]+(?:\s+[а-яё-]+)?)$/u);
  if (m) {
    const minute = minutesFromText(m[2]);
    if (minute !== null && (minute > 9 || /\s/u.test(m[2]))) return done(clock(Number(m[1]), minute));
    return null;
  }
  // Слово часов и число минут: «десять 30».
  m = v.match(/^([а-яё-]+)\s+(\d{1,2})$/u);
  if (m) return done(clock(numFromText(m[1]), Number(m[2])));
  // Только слова: «десять тридцать», «двадцать два», «двадцать два тридцать».
  const words = v.split(/\s+/).filter(Boolean);
  if (words.every((x) => /^[а-яё-]+$/u.test(x))) {
    if (words.length === 1) return done(clock(numFromText(words[0]), 0));
    if (words.length === 2) {
      // «двадцать два» — одно число 22, а не 20 часов 2 минуты: десяток плюс
      // единица. «десять тридцать» — час и минуты.
      const whole = numFromText(v);
      const tensFirst = TENS[words[0]] !== undefined;
      const unitSecond = NUM_WORDS[words[1]];
      if (whole !== null && whole <= 23 && tensFirst && unitSecond !== undefined && unitSecond < 10)
        return done(clock(whole, 0));
      return done(clock(numFromText(words[0]), minutesFromText(words[1])));
    }
    if (words.length === 3) {
      // «девять ноль пять» — час, «ноль», минуты: 09:05.
      if (/^(?:ноль|нуль)$/u.test(words[1])) {
        const h = numFromText(words[0]);
        const m = numFromText(words[2]);
        if (h !== null && m !== null) return done(clock(h, m));
      }
      // «двадцать два тридцать» — час из двух слов, минуты из третьего.
      // «десять тридцать пять» — час из первого, минуты из двух остальных.
      if (TENS[words[0]] !== undefined && NUM_WORDS[words[1]] !== undefined)
        return done(clock(numFromText(words[0] + " " + words[1]), minutesFromText(words[2])));
      return done(clock(numFromText(words[0]), minutesFromText(words[1] + " " + words[2])));
    }
    return null;
  }
  // Одно число — целый час.
  return done(clock(numFromText(v), 0));
}

/**
 * Разбирает время, отбрасывая лишние слова справа.
 *
 * Нужно для случаев, когда шаблон захватил больше, чем относится ко времени:
 * «в 8 два хлеба» — «восемь» это час, а «два» — количество (два хлеба).
 * Полная запись не разбирается, и тогда пробуем всё более короткие начала,
 * пока не получится время. Длина разобранного возвращается в `length`.
 *
 * @returns {{hour:number, minute:number, length:number}|null}
 */
/**
 * Разбирает время, отбрасывая лишние слова справа.
 *
 * Нужно, когда шаблон захватил больше, чем относится ко времени:
 *  • «в 8 два хлеба» — «восемь» это час, а «два» — количество (два хлеба);
 *  • «16:00 тридцать человек» — «тридцать» тоже количество.
 * Полная запись не разбирается — пробуем всё более короткие начала.
 *
 * Числа справа НЕ отрезаем: голое число после часа почти всегда дата или
 * другая запись («в 16 25 мая») — такие случаи разбирает minutesAfterHour.
 *
 * @returns {{hour:number, minute:number, length:number}|null}
 */
export function parseClockPrefix(text, whole = "") {
  const src = String(text || "");
  const words = src.split(/\s+/).filter(Boolean);
  for (let n = words.length; n >= 1; n--) {
    const cut = words.slice(0, n).join(" ");
    const dropped = words.slice(n);
    // Отрезаем только слова: число справа — не хвост времени.
    if (dropped.some((x) => /\d/u.test(x))) return null;
    const c = parseClockText(cut, whole);
    if (!c) continue;
    let length = src.indexOf(cut) + cut.length;
    // «минут» сразу за временем тоже относится ко времени.
    if (whole) {
      const at = whole.indexOf(src);
      const tail = at < 0 ? "" : whole.slice(at + length);
      const m = tail.match(/^\s+минут[а-яё]*/u);
      if (m) length += m[0].length;
    }
    return { ...c, length };
  }
  return null;
}

/** Отвергнуты ли минуты-слова после двоеточия из-за следующего слова. */
function trailingMinutesRejected(src, whole) {
  if (!/:\d{1,2}\s+[а-яё]/u.test(src)) return false;
  const at = whole ? whole.indexOf(src) : -1;
  const tail = at < 0 ? "" : whole.slice(at + src.length);
  const next = firstWord(tail);
  return Boolean(next) && !VERB_AFTER.test(next) && !/^минут/u.test(next);
}

/** Сколько символов идёт до места, с которого начинается другая запись. */
function leadLength(text, token) {
  return String(text).indexOf(token);
}

/**
 * Минуты сразу после часа — слово или цифры.
 *
 * Распознаватель рвёт время на части: «10:00 тридцать», «10:00 30». Минуты
 * принимаются, но с оглядкой на контекст:
 *  • цифры не берутся, если следом стоит месяц или «числа»: «в 16 25 мая» —
 *    это дата, а не время;
 *  • слова принимаются, только если за ними конец фразы, «минут» или глагол
 *    действия: за количеством идёт существительное («в 8 два хлеба»).
 *
 * @param {string} tail — текст сразу после прочитанного часа
 * @returns {{minutes:number, eat:number, nextWord:string|null}|null}
 *   eat — сколько символов хвоста относится к минутам.
 */
export function minutesAfterHour(tail) {
  const t = String(tail || "");
  // Цифры: «30», «5».
  const dg = t.match(/^\s+(\d{1,2})(?![\d:.])/u);
  if (dg) {
    const value = Number(dg[1]);
    if (value > 59) return null;
    const rest = t.slice(dg[0].length);
    const word = firstWord(rest);
    if (word && (isMonthWord(word) || /^(?:числа|го|года|году|г)$/u.test(norm(word))))
      return null;
    let eat = dg[0].length;
    const minPart = rest.match(/^\s+минут[а-яё]*/u);
    if (minPart) eat += minPart[0].length;
    return { minutes: value, eat, nextWord: null };
  }
  // Слова: «тридцать», «двадцать пять». Берём одно слово, и только если оно
  // само по себе даёт минуты; иначе пробуем пару слов.
  const rest = t.replace(/^\s+/, "");
  if (!rest) return null;
  const tokens = rest.match(/^[а-яё-]+(?:\s+[а-яё-]+)?/u);
  if (!tokens) return null;
  const pair = tokens[0];
  const single = pair.split(/\s+/)[0];
  const afterPair = rest.slice(pair.length);
  const afterSingle = rest.slice(single.length);

  const tryWord = (text, tail2, lead) => {
    const value = minutesFromText(text);
    if (value === null) return null;
    // «минут» сразу после слова входит в минуты.
    const minPart = tail2.match(/^\s+минут[а-яё]*/u);
    let eat = lead + text.length;
    if (minPart) eat += minPart[0].length;
    const nextWord = firstWord(minPart ? tail2.slice(minPart[0].length) : tail2);
    // За количеством идёт существительное — это не минуты.
    if (nextWord && !VERB_AFTER.test(nextWord)) return null;
    return { minutes: value, eat, nextWord };
  };

  return (
    tryWord(pair, afterPair, t.length - rest.length) ||
    tryWord(single, afterSingle, t.length - rest.length)
  );
}

/** Сколько символов занимает часть суток сразу после часа, если она есть. */
export function daypartTailLength(tail) {
  const m = String(tail || "").match(new RegExp("^\\s+(?:" + DAYPART_RE.source + ")" + RB, "u"));
  return m ? m[0].length : 0;
}

// ---------------------------------------------------------------------------
// Единый шаблон времени.
//
// Это второе, что живёт только здесь: определение того, КАК выглядит время в
// тексте. Разбор (что оно значит) — в parseClockText выше. Все три модуля
// берут шаблон отсюда, поэтому новая форма появляется сразу везде, а не в
// одном слое из трёх.
//
// Шаблон намеренно «широкий»: он может поймать и дату («16 25 мая», «15.10»).
// Решение принимает разбор: parseClockText вернёт null, и вызывающий код
// такую запись временем не признаёт. Так проверка остаётся в одном месте.
// ---------------------------------------------------------------------------

const numKeys = [
  ...Object.keys(TENS),
  ...Object.keys(NUM_WORDS),
  ...Object.keys(NUM_WORDS_GENITIVE),
].sort((a, b) => b.length - a.length);

/** Число: цифры или слово, включая составные («двадцать пять»). */
export const NUM_SRC =
  // (?!\d) обязателен: без него «16 25 мая» разбиралось как «16 2» — шаблон
  // откусывал от «25» одну цифру, и дата превращалась во время 16:02.
  "(?:\\d{1,2}(?!\\d)|(?:" +
  Object.keys(TENS).sort((a, b) => b.length - a.length).join("|") +
  ")(?:[-\\s]+(?:один|одна|одно|два|две|три|четыре|пять|шесть|семь|восемь|девять))?|" +
  numKeys.filter((k) => !(k in TENS)).join("|") +
  ")";

/** Порядковое числительное: «одиннадцатого». */
export const ORD_SRC = "(?:" + Object.keys(ORDINALS).join("|") + ")";

/** Части суток: «вечера». */
export const DAYPART_SRC = "(?:" + Object.keys(PARTS_OF_DAY).join("|") + ")";

/** Названия месяцев — чтобы «16 25 мая» не стало временем. */
export const MONTH_SRC = "(?:" + MONTH_WORDS.join("|") + ")";

/**
 * Шаблон времени. Порядок веток — от длинных форм к коротким: иначе
 * «двадцать пять» разберётся как «двадцать», а «пять» останется в тексте.
 *
 * Ветки:
 *  1. «без пятнадцати шесть» — минуты до часа;
 *  2. «тридцать минут одиннадцатого» — минуты и порядковое число часа;
 *  3. «половина одиннадцатого», «пол-одиннадцатого», «полдевятого»;
 *  4. «четверть одиннадцатого»; «шесть с четвертью»;
 *  5. «10:30», «10:30:00»; «10.30»;
 *  6. «10 часов 30 минут», «десять часов»;
 *  7. два числа подряд: «10 30», «десять тридцать», «двадцать два тридцать»;
 *  8. одно число или слово: «10», «десять»;
 *  9. «полдень», «полночь», «обед».
 */
/**
 * Оборот «без N <час>»: «без четверти шесть», «без двадцати пяти шесть».
 * Вынесен отдельно, потому что это единственная форма времени, которая
 * называется без предлога «в» и без слова «час».
 */
export const BEZ_SRC =
  "без\\s+(?:четверти|половины|" +
  TENS_GEN_SRC + "|" + NUM_SRC +
  ")(?:\\s+минут[а-яё]*)?\\s+(?:" +
  // Час после «без» называют и количественным («без пятнадцати шесть»), и
  // порядковым («без пятнадцати шестого»). Вторая форма — та же самая: в ней
  // назван час, к которому идёт отсчёт назад. Без неё шаблон обрывался на
  // «шесть» внутри «шестого», и время находилось по обрывку «пятнадцати».
  //
  // Порядковое идёт первым и с границей слова: иначе «шесть» совпало бы с
  // началом «шестого», хвост «ого» остался бы в тексте, а часть суток
  // («шестого вечера») не попала бы во время.
  "(?:" + ORD_SRC + "|" + NUM_SRC + ")" + RB + ")";

export const CLOCK_SRC =
  "(?:" +
  [
    // 1 — минуты до часа.
    BEZ_SRC,
    // 2
    NUM_SRC + "\\s+минут[а-яё]*\\s+" + ORD_SRC,
    // 3
    // 3 — пробел обязателен: «половина одиннадцатого» — два слова, а
    // «полдевятого» — одно. Без \s+ форма «половине одиннадцатого» не
    // находилась вовсе, и время оставалось пустым.
    "(?:половин[а-яё]*\\s+|пол[-\\s]?)" + ORD_SRC,
    // 4
    "четверть\\s+" + ORD_SRC,
    NUM_SRC + "\\s+с\\s+четвертью",
    // 5 — цифры с двоеточием. Форма с минутами словами («16:00 тридцать»)
    // идёт раньше простой: иначе «16:00» съелось бы без минут. Составные
    // минуты («двадцать пять») тоже часть числа.
    "\\d{1,2}:\\d{1,2}\\s+" + NUM_SRC + "(?:\\s+" + NUM_SRC + ")?(?:\\s+минут[а-яё]*)?",
    "\\d{1,2}:\\d{1,2}(?::\\d{1,2})?",
    "\\d{1,2}\\.\\d{1,2}(?![\\d.])",
    // 6
    NUM_SRC + "\\s+час[а-яё]*(?:\\s+" + NUM_SRC + "\\s*минут[а-яё]*)?",
    // 7 — часы и минуты словами или цифрами. Перед названием месяца это
    // дата, а не время: «16 25 мая».
    // Трёхсловная форма («девять ноль пять») идёт первой: иначе шаблон
    // разобрал бы её как два отдельных времени.
    NUM_SRC + "\\s+(?:ноль|нуль)\\s+" + NUM_SRC,
    "(?:" +
      NUM_SRC + "\\s+" + NUM_SRC +
      ")(?!\\s+(?:" + MONTH_SRC + "|числа|го|года|году))",
    // 8 — одно число или слово, но НЕ перед названием месяца: «16 мая» —
    // это дата. Хвост проверяем просмотром, чтобы не откусить месяц.
    NUM_SRC + "(?!\\s+(?:" + MONTH_SRC + "|числа|го|года|году))",
    // 9
    "(?:полдень|полудня|полночь|полуночи|обед)",
  ].join("|") +
  ")" +
  // Часть суток после времени: «в десять вечера».
  "(?:\\s+" + DAYPART_SRC + ")?";

/** Регулярка времени для поиска по тексту (флаг g — искать все вхождения). */
export function clockRegex(flags = "giu") {
  return new RegExp(CLOCK_SRC, flags);
}

