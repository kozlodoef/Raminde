// Найденные дефекты разбора «дата + время» в одной фразе.
//
// Каждый случай ниже действительно ломался: проверка идёт по обоим путям —
// голосовому (parseReminder в timeParser) и редактору поля ввода
// (parseEditor). Расхождение между ними — отдельный класс ошибок: человек
// диктует и печатает одно и то же, а получает разное.
import test from "node:test";
import assert from "node:assert/strict";

import { parseEditor, editorPhrase } from "../src/domain/home-editor.js";
import { parseGroup } from "../src/domain/groups.js";
import { parseReminder } from "../src/lib/timeParser.js";
import { spokenDate, dateComplaint } from "../src/domain/dates-spoken.js";
import { isMonthWord, minutesAfterHour } from "../src/domain/time-lexicon.js";

// Вторник, 25 ноября 2026, 21:00 по местному времени.
const NOW = new Date(2026, 10, 25, 21, 0, 0);
const ISO = (d) =>
  d.getFullYear() +
  "-" +
  String(d.getMonth() + 1).padStart(2, "0") +
  "-" +
  String(d.getDate()).padStart(2, "0");
const blank = () => ({
  id: "d",
  text: "",
  selectedDates: [],
  dates: [],
  times: [],
  color: "#000",
});

// --- 1. Название месяца в любом падеже ---
//
// isMonthWord сверял ОСНОВУ месяца с целым словом через «^основа$».
// Совпадал только «мая» (записан формой целиком); «декабря», «ноября»,
// «марта» не распознавались никогда. Из-за этого рушилась защита «минуты
// не перед месяцем»: «в 16 25 декабря» разбиралось как 16:25.

test("месяц распознаётся в любом падеже", () => {
  for (const w of [
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
  ])
    assert.equal(isMonthWord(w), true, "не распознан месяц: " + w);
});

test("обычные слова не считаются месяцем", () => {
  for (const w of ["мартышку", "майонез", "июньский", "купить", "маяк"])
    assert.equal(isMonthWord(w), false, "ложное срабатывание: " + w);
});

test("перед названием месяца минуты не берутся", () => {
  for (const t of [" 25 декабря", " 25 ноября", " 25 марта", " 30 января"])
    assert.equal(minutesAfterHour(t), null, "минуты съели дату: " + t);
});

test("«в 16 25 декабря» — это 16:00 и 25 декабря, а не 16:25", () => {
  const r = parseEditor("в 16 25 декабря встреча", blank(), NOW);
  assert.deepEqual(r.times, ["16:00"]);
  assert.deepEqual(r.dates, ["2026-12-25"]);
});

test("«22 05» остаётся временем: час больше 12", () => {
  const r = parseEditor("в 22 05 позвонить", blank(), NOW);
  assert.deepEqual(r.times, ["22:05"]);
});

// --- 2. Год со словом «года» ---
//
// Шаблон принимал только голое число года: «2027». В форме «2027 года»
// слово оставалось в тексте напоминания — получалось «Года вылет».

test("«2027 года» не оставляет «года» в тексте", () => {
  for (const phrase of [
    "пятого мая 2027 года в 10:00 вылет",
    "5 мая 2027 года в 10:00 вылет",
    "пятого мая 2027 г. в 10:00 вылет",
    "5 мая 2027 в 10:00 вылет",
  ]) {
    const r = parseEditor(phrase, blank(), NOW);
    assert.equal(r.text, "Вылет", `лишние слова для «${phrase}»: ${r.text}`);
    assert.deepEqual(r.dates, ["2027-05-05"], "дата для «" + phrase + "»");
  }
});

test("голосовой путь тоже понимает «года»", () => {
  const r = parseReminder("пятого мая 2027 года в 10:00 вылет", NOW);
  assert.equal(r.text, "Вылет");
  assert.equal(new Date(r.when).getFullYear(), 2027);
  assert.equal(new Date(r.when).getMonth(), 4);
  assert.equal(new Date(r.when).getDate(), 5);
});

// --- 3. 29 февраля ---
//
// Проверка «существует ли день» шла раньше поиска года, и в невисокосный
// год «двадцать девятого февраля» отбрасывалось целиком: фраза рассыпалась,
// а напоминание молча вставало на сегодня.

test("29 февраля переносится на ближайший високосный год", () => {
  const r = parseEditor("двадцать девятого февраля в 12:00 проверить", blank(), NOW);
  assert.deepEqual(r.dates, ["2028-02-29"]);
  assert.deepEqual(r.times, ["12:00"]);
  assert.equal(r.text, "Проверить");
});

test("29 февраля через голосовой путь", () => {
  const r = parseReminder("двадцать девятого февраля в 12:00 проверить", NOW);
  assert.equal(ISO(new Date(r.when)), "2028-02-29");
});

// --- 4. Несуществующая дата ---
//
// «30 февраля», «31 апреля» раньше молча превращались в напоминание на
// сегодня, и человек был уверен, что поставил его на другой день.

test("невозможная дата объясняется, а не подменяется сегодняшней", () => {
  for (const phrase of [
    "тридцатого февраля в 12:00 проверить",
    "тридцать первого апреля в 10:00 отчёт",
    "тридцать первое ноября в 10:00 отчёт",
  ]) {
    const r = parseEditor(phrase, blank(), NOW);
    assert.ok(
      r.issues.some((e) => /не бывает/i.test(e)),
      `нет объяснения для «${phrase}»: ${JSON.stringify(r.issues)}`,
    );
    // Обрывок даты не должен оставаться в тексте напоминания.
    assert.ok(
      !/феврал|апрел|ноябр/i.test(r.text || ""),
      `дата осталась в тексте «${phrase}»: ${r.text}`,
    );
  }
});

test("одно объяснение, а не два разных", () => {
  const r = parseEditor("29.02.2027 в 12:00 проверить", blank(), NOW);
  const about = r.issues.filter((e) => /даты/i.test(e));
  assert.equal(about.length, 1, "дубли сообщений: " + JSON.stringify(r.issues));
});

test("dateComplaint молчит про существующие даты", () => {
  for (const p of [
    "двадцать пятого декабря в 12:00",
    "тридцать первого декабря в 12:00",
    "29 февраля",
  ])
    assert.equal(dateComplaint(p, NOW), null, "ложная жалоба: " + p);
});

// --- 5. Согласованность путей ---
//
// Один и тот же текст, сказанный голосом и напечатанный, должен давать одну
// и ту же дату. Раньше «года» и 29 февраля расходились между путями.

test("голос и клавиатура дают одинаковую дату", () => {
  for (const phrase of [
    "двадцать пятого декабря в 12:00 проверить",
    "пятого мая 2027 года в 10:00 вылет",
    "двадцать девятого февраля в 12:00 проверить",
    "завтра в семь утра полить цветы",
  ]) {
    const viaEditor = parseEditor(phrase, blank(), NOW).dates;
    const viaVoice = parseReminder(phrase, NOW).when;
    assert.equal(viaEditor.length, 1, "редактор не нашёл дату: " + phrase);
    assert.equal(
      viaEditor[0],
      ISO(new Date(viaVoice)),
      `расхождение путей для «${phrase}»`,
    );
  }
});

// --- 6. Соседние случаи не должны пострадать ---

test("дата без месяца по-прежнему работает", () => {
  assert.deepEqual(spokenDate("двадцать пятого декабря", NOW).date, "2026-12-25");
  // Без месяца берётся ближайший такой день. Сегодня 25-е, поэтому
  // «двадцать пятого» — это сегодня, а не следующий месяц. Время 12:00 к
  // 21:00 уже прошло, и сохранение такое напоминание отклонит — это
  // отдельная защита PAST_TIME_MESSAGE, а не ошибка разбора.
  const r = parseEditor("двадцать пятого в 12:00 позвонить", blank(), NOW);
  assert.deepEqual(r.dates, ["2026-11-25"]);
  assert.deepEqual(r.times, ["12:00"]);
});

test("дата без месяца в будущем времени принимается", () => {
  // 12:00 ещё впереди относительно 6 утра — вот здесь проверяем именно
  // разбор, а не защиту от прошедшего времени.
  const morning = new Date(2026, 10, 25, 6, 0, 0);
  const r = parseEditor("двадцать пятого в 12:00 позвонить", blank(), morning);
  assert.deepEqual(r.dates, ["2026-11-25"]);
  assert.deepEqual(r.times, ["12:00"]);
});

test("время рядом с датой не съедает минуты", () => {
  const r = parseEditor("двадцать пятого декабря в 19:30 полить цветы", blank(), NOW);
  assert.deepEqual(r.times, ["19:30"]);
  assert.deepEqual(r.dates, ["2026-12-25"]);
});

test("количество не становится временем", () => {
  const r = parseEditor("в 8 два хлеба", blank(), NOW);
  assert.deepEqual(r.times, ["08:00"]);
  assert.match(r.text, /Два хлеба/i);
});

test("одинокое число не время без признака часа", () => {
  const r = parseGroup("купить 2 хлеба", [], NOW);
  assert.deepEqual(r.times, []);
});

// --- 7. Инварианты, установленные раньше ---
//
// Эти случаи уже разбирались верно, и правки дат не должны были их тронуть.
// Проверка нужна именно сейчас: защита «минуты не перед месяцем» живёт в
// том же месте, что и определение месяца, — ошибка в одном ломает другое.

test("дата и время рядом не путаются", () => {
  const cases = [
    ["в 16 25 мая встреча", ["16:00"], ["2027-05-25"]],
    ["в 12 25 декабря встреча", ["12:00"], ["2026-12-25"]],
    ["в 10.30 встреча", ["10:30"], []],
    ["в 15.10 встреча", [], ["2027-10-15"]],
    ["в 25.12 встреча", [], ["2026-12-25"]],
    ["в 10 30 встреча", ["10:30"], []],
  ];
  for (const [phrase, times, dates] of cases) {
    const r = parseEditor(phrase, blank(), NOW);
    assert.deepEqual(r.times, times, "время для «" + phrase + "»");
    assert.deepEqual(r.dates, dates, "дата для «" + phrase + "»");
  }
});

test("количество рядом с часом не становится минутами", () => {
  const r = parseEditor("16:00 тридцать человек придут", blank(), NOW);
  assert.deepEqual(r.times, ["16:00"]);
  assert.match(r.text, /Тридцать человек/i);
});

test("полунабранное время не переписывается", () => {
  // Человек печатает «в 10:» — это ещё не время, но и не повод стирать.
  const r = parseEditor("в 10:", blank(), NOW);
  assert.deepEqual(r.times, ["10:00"]);
});

test("«через час» хранит настоящее время, а не значение по умолчанию", () => {
  // В сохранённом правиле рядом с верным at лежало чужое times — «09:00»
  // из шаблона расписания. Срабатывание не ломалось, но данные были
  // противоречивыми, и карточка могла показать не то время.
  const r = parseEditor("через два часа позвонить", blank(), NOW);
  assert.equal(r.schedule.kind, "once");
  assert.deepEqual(r.schedule.times, ["23:00"]);
  assert.equal(ISO(new Date(r.schedule.at)), "2026-11-25");
});

// --- 8. Диапазон «с 9 до 11» ---
//
// Проект не поддерживает интервалы: время одно. Важно, чтобы такой оборот
// не превращался в ложное время и чтобы об этом было сказано. Сейчас
// выводится «Во сколько напомнить?» — это верно.

test("интервал не превращается во время и о нём спрашивают", () => {
  const r = parseEditor("двадцать пятого декабря с 9 до 11 встреча", blank(), NOW);
  assert.deepEqual(r.dates, ["2026-12-25"]);
  assert.deepEqual(r.times, []);
  assert.ok(
    r.issues.some((e) => /Во сколько/i.test(e)),
    "нет вопроса о времени: " + JSON.stringify(r.issues),
  );
});

// --- 9. Отображение в поле ввода ---
//
// В поле дата и время показываются цифрами — так ошибку распознавания легче
// заметить. Слово «года» рядом с уже переведённой датой было лишним:
// «05.05 2027 года в 10:00 вылет».

test("слово «года» не остаётся рядом с цифровой датой", () => {
  const cases = [
    ["5 мая 2027 года в 10:00 вылет", "05.05 2027 в 10:00 вылет"],
    ["пятого мая 2027 г. в 10:00 вылет", "05.05 2027 в 10:00 вылет"],
    ["двадцать пятого декабря в 19:30 полить", "25.12 в 19:30 полить"],
    ["25 декабря в 19:30 полить", "25.12 в 19:30 полить"],
  ];
  for (const [phrase, shown] of cases) {
    const r = parseEditor(phrase, blank(), NOW);
    assert.equal(
      editorPhrase(r, NOW),
      shown,
      "показ для «" + phrase + "»",
    );
  }
});