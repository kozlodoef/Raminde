import test from "node:test";
import assert from "node:assert/strict";

import { toDigits } from "../src/domain/phrase-digits.js";

// 25 ноября 2026, 17:00.
const NOW = new Date(2026, 10, 25, 17, 0, 0);

/**
 * Что человек увидит в поле ввода после диктовки.
 *
 * Проверяем именно подпись: раньше «двадцать шестого» показывалось как
 * «20:00 шестого», хотя напоминание ставилось на 26-е верно. Разбор был
 * правильный, а подпись — нет, и это сбивало с толку.
 */
const shown = (phrase) => toDigits(phrase, {}, NOW);

// --- День без названия месяца ---

test("«двадцать шестого» показывается датой, а не временем", () => {
  assert.equal(
    shown("двадцать шестого в 07:45 посмотреть телевизор"),
    "26.11 в 07:45 посмотреть телевизор",
  );
});

test("«шестого» показывается датой следующего месяца", () => {
  // 6-е в ноябре уже прошло — значит ближайшее 6-е это декабрь.
  assert.equal(
    shown("шестого в 07:45 посмотреть телевизор"),
    "06.12 в 07:45 посмотреть телевизор",
  );
});

test("«пятого» показывается датой", () => {
  assert.equal(shown("пятого в 09:00 позвонить"), "05.12 в 09:00 позвонить");
});

test("«первого» показывается датой", () => {
  assert.equal(shown("первого в 09:00 позвонить"), "01.12 в 09:00 позвонить");
});

// --- Обороты времени не должны стать датой ---

test("«половина одиннадцатого» остаётся временем", () => {
  assert.equal(shown("в половине одиннадцатого позвонить"), "в 10:30 позвонить");
});

test("«четверть седьмого» остаётся временем", () => {
  assert.equal(shown("в четверть седьмого позвонить"), "в 06:15 позвонить");
});

test("«без четверти шесть» остаётся временем", () => {
  assert.equal(shown("в без четверти шесть позвонить"), "в 05:45 позвонить");
});

test("«без пятнадцати шестого» остаётся временем, а не датой", () => {
  // «Шестого» здесь называет час, к которому идёт отсчёт назад, а не день
  // месяца. Раньше его принимали за 6-е число и получалось «05:35.12».
  assert.equal(shown("напомни без пятнадцати шестого позвонить"), "напомни в 05:45 позвонить");
});

test("«без двадцати пяти шестого» остаётся временем", () => {
  assert.equal(
    shown("напомни без двадцати пяти шестого позвонить"),
    "напомни в 05:35 позвонить",
  );
});

// --- Число после времени — это минуты, а не день ---

test("«в 16:00 тридцать» — это 16:30, а не 30-е число", () => {
  assert.equal(
    shown("напомни поесть картошки в 16:00 тридцать"),
    "напомни поесть картошки в 16:30",
  );
});

test("«в 17:00 двадцать пять» — это 17:25", () => {
  assert.equal(
    shown("напомни в 17:00 двадцать пять покушать"),
    "напомни в 17:25 покушать",
  );
});

test("количество после времени не превращается в дату", () => {
  assert.equal(
    shown("напомни в 15:30 двадцать пять человек"),
    "напомни в 15:30 двадцать пять человек",
  );
  assert.equal(
    shown("напомни в 16:00 тридцать человек придут"),
    "напомни в 16:00 тридцать человек придут",
  );
});

// --- Дата с названием месяца по-прежнему работает ---

test("«двадцать пятого декабря» — дата", () => {
  assert.equal(
    shown("двадцать пятого декабря в 19:30 купить подарки"),
    "25.12 в 19:30 купить подарки",
  );
});
