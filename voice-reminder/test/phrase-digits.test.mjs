// Тесты перевода даты и времени в цифры (domain/phrase-digits.js).
//
// Смысл проверок: в поле редактора пользователь должен видеть «18.11 в 07:00»,
// а не «завтра в семь утра». При этом текст напоминания не должен теряться
// и не должен дублировать предлог.
import test from "node:test";
import assert from "node:assert/strict";
import { toDigits, shortDate } from "../src/domain/phrase-digits.js";

const now = new Date("2026-11-17T21:00:00+04:00");

const cases = [
  // [что сказано, что должно получиться]
  ["напомни завтра в семь утра полить цветы", "напомни 18.11 в 07:00 полить цветы"],
  ["напомни сегодня в 9 позвонить", "напомни 17.11 в 09:00 позвонить"],
  ["напомни послезавтра в десять утра дела", "напомни 19.11 в 10:00 дела"],
  ["напомни 15 декабря в 18:00 поздравить Алёну", "напомни 15.12 в 18:00 поздравить Алёну"],
  ["напомни 31 декабря в 12:00 поздравить всех", "напомни 31.12 в 12:00 поздравить всех"],
  ["напомни 20 ноября в 9:00 врач", "напомни 20.11 в 9:00 врач"],
  ["напомни через два часа позвонить маме", "напомни через 2 ч позвонить маме"],
  ["напомни через полчаса выключить плиту", "напомни через 30 мин выключить плиту"],
  ["напомни в пятницу вечером купить подарок", "напомни 20.11 вечером купить подарок"],
  ["напомни в понедельник в 10 утра совещание", "напомни 23.11 в 10:00 совещание"],
  // Обороты с долями часа: предлог не должен задвоиться.
  ["напомни в четверть седьмого утра зарядка", "напомни в 06:15 зарядка"],
  ["напомни в половине восьмого вечера ужин", "напомни в 19:30 ужин"],
  ["напомни без четверти шесть вечера забрать", "напомни в 17:45 забрать"],
  // Слово суток после цифрового времени убирается как избыточное.
  ["напомни в 4:00 дня поесть картошки", "напомни в 4:00 поесть картошки"],
];

for (const [input, expected] of cases) {
  test(`цифры: «${input}»`, () => {
    assert.equal(toDigits(input, {}, now), expected);
  });
}

test("текст напоминания не теряется при замене", () => {
  const input = "напомни завтра в семь утра полить цветы и вынести мусор";
  const out = toDigits(input, {}, now);
  assert.ok(out.includes("полить цветы"), "первая часть текста на месте");
  assert.ok(out.includes("вынести мусор"), "вторая часть текста на месте");
});

test("фраза без даты и времени не меняется", () => {
  const input = "напомни купить хлеб";
  assert.equal(toDigits(input, {}, now), input);
});

test("пустая строка и мусор не ломают функцию", () => {
  assert.equal(toDigits("", {}, now), "");
  assert.equal(toDigits(null, {}, now), null);
  assert.equal(toDigits(undefined, {}, now), undefined);
});

test("shortDate: текущий год без года, чужой — с годом", () => {
  assert.equal(shortDate(new Date("2026-11-18T10:00:00+04:00"), now), "18.11");
  assert.equal(shortDate(new Date("2027-01-05T10:00:00+04:00"), now), "05.01.2027");
});

test("переход через месяц и год считается верно", () => {
  // От 31 декабря «завтра» — это 1 января следующего года.
  const ny = new Date("2026-12-31T22:00:00+04:00");
  assert.equal(toDigits("напомни завтра в 9 утра", {}, ny), "напомни 01.01.2027 в 09:00");
});
