import test from "node:test";
import assert from "node:assert/strict";

/**
 * Всплывающее сообщение (пузырь) — только про сбой.
 *
 * Правило появилось после того, как пузыри всплывали после каждого успешного
 * действия: «Удалено напоминаний: 2», «Время изменено на 19:30»,
 * «Напоминание удалено со всех дат.». Всё это видно и без пузыря — по пустому
 * дню, по новому времени в карточке, по исчезнувшей карточке. Пузырь поверх
 * экрана закрывает календарь и мешает, поэтому его бережём для случаев, когда
 * что-то действительно не получилось.
 *
 * Тест проверяет исходник: он ловит возврат подтверждений успеха в пузырь.
 * Это дешёвая защита, потому что весь разбор живёт в App.jsx, а рендер
 * компонента в node без DOM не проверить.
 */
const source = await (await import("node:fs/promises")).readFile(
  new URL("../src/App.jsx", import.meta.url),
  "utf8",
);

test("подтверждений успеха в пузыре нет", () => {
  // Формулировки, которые раньше всплывали поверх экрана как достижение.
  const successes = [
    /setMessage\(`Удалено напоминаний/,
    /setMessage\(`Время изменено на/,
    /setMessage\("Напоминание удалено со всех дат\."\)/,
    /setMessage\("Напоминание сохранено/,
  ];
  for (const re of successes)
    assert.ok(!re.test(source), `пузырь на успех вернулся: ${re}`);
});

test("подсказка про дату идёт тихой строкой, а не пузырём", () => {
  // dateNote — пояснение, а не ошибка. Её место в списке с note.
  assert.match(source, /setNote\(isPro\(bill\) \? "" : dateNote\(current\)\)/);
  assert.ok(
    !/setMessage\(isPro\(bill\) \? "" : dateNote/.test(source),
    "dateNote снова уходит в пузырь",
  );
});

test("тихая строка есть в разметке и имеет свой стиль", () => {
  assert.match(source, /className="editor-note"/);
});
