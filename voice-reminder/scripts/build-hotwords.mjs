/**
 * Фразы из каталога TIME_FORMS.
 *
 * Каталог хранит целые фразы («напомни в половине одиннадцатого позвонить»),
 * а контекстному смещению нужны отдельные слова. Поэтому фразу разбиваем на
 * слова, выбрасываем служебное «напомни» и оставляем всё остальное: слова
 * времени окажутся в списке вместе со своими формами.
 */
function fromTimeForms() {
  const out = new Set();
  for (const form of TIME_FORMS) {
    for (const word of String(form.phrase || "").toLowerCase().split(/\s+/)) {
      if (!word || word === "напомни") continue;
      if (!/^[а-яё-]+$/u.test(word)) continue;
      out.add(word);
    }
  }
  return [...out];
}

/**
 * Фразы из напоминаний пользователя.
 *
 * Считается локально и никуда не отправляется: пути к сохранённым
 * напоминаниям ищутся рядом с приложением, и если их нет — шаг пропускается.
 * Файлы читаются как текст и разбираются регуляркой, потому что напоминания
 * хранятся в разных форматах (localStorage и нативный store).
 */
function fromReminders() {
  const candidates = [
    join(root, "reminders.json"),
    join(root, "local-reminders.json"),
    join(process.env.USERPROFILE || "", "voice-reminder-reminders.json"),
  ];
  const counts = new Map();
  const ignore = new Set([
    "напомни", "напомнить", "и", "в", "во", "на", "по", "с", "до", "мне",
    "нам", "не", "забудь", "пожалуйста", "что", "чтобы", "про",
  ]);
  for (const file of candidates) {
    if (!file || !existsSync(file)) continue;
    let raw = "";
    try {
      raw = readFileSync(file, "utf8");
    } catch {
      continue;
    }
    for (const word of raw.toLowerCase().match(/[а-яё-]{3,}/gu) || []) {
      if (ignore.has(word)) continue;
      counts.set(word, (counts.get(word) || 0) + 1);
    }
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([w]) => w)
    .slice(0, 50);
}

function build() {
  const seen = new Set();
  const out = [];
  const push = (word) => {
    const w = String(word || "").trim().toLowerCase();
    if (!w || seen.has(w)) return;
    if (!/^[а-яё][а-яё\s-]*$/u.test(w)) return;
    seen.add(w);
    out.push(w);
  };

  // Порядок = приоритет: он же порядок строк в файле, и первые записи
  // получают больше веса при усечении до MAX_ENTRIES.
  CRITICAL.forEach(push);
  fromReminders().forEach(push);
  WEEKDAYS.forEach(push);
  MONTH_FORMS.forEach(push);
  ORDINAL_DAYS.forEach(push);
  PARTS_OF_DAY.forEach(push);
  fromTimeForms().forEach(push);

  return out.slice(0, MAX_ENTRIES);
}

const entries = build();
mkdirSync(dirname(OUT), { recursive: true });
// Пишем с LF и без BOM: sherpa-onnx читает файл построчно и на BOM в первой
// строке спотыкается — первое слово молча не попадает в контекстный граф
// («Cannot find ID for token ﻿послезавтра»).
writeFileSync(OUT, entries.join("\n") + "\n", { encoding: "utf8" });

console.log(`hotwords: ${entries.length} записей → ${OUT}`);
console.log(`первые: ${entries.slice(0, 12).join(", ")}`);
