// scripts/build-hotwords.mjs — собирает список hotwords для sherpa-onnx.
//
// Зачем. sherpa-onnx умеет contextual biasing: список слов, на которые модель
// «опирается» при выборе гипотез. Для этого приложения полезны обороты,
// которых в обычной речи мало, а в напоминаниях много: «послезавтра»,
// «полчетвёртого», названия месяцев, части суток. Без такого списка модель
// слышит их как похожие обычные слова — «полчетвёртого» превращается в
// «пол четвёртого», а «послезавтра» в «после завтра».
//
// Список собирается из тех же таблиц, по которым работает разбор: добавляя
// форму в лексикон, вы получаете её и в hotwords при следующем прогоне.
//
// Запуск: node scripts/build-hotwords.mjs
// Файл: android/app/src/main/assets/sherpa/hotwords.txt
//
// Контекстное смещение работает с любовью к частоте: слишком длинный список
// размывает веса, поэтому объём ограничен (см. MAX_ENTRIES), а самые ценные
// слова идут первыми.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { TIME_FORMS } from "../src/domain/time-lexicon.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const OUT = join(root, "android", "app", "src", "main", "assets", "sherpa", "hotwords.txt");

/**
 * Предел объёма файла.
 *
 * sherpa-onnx строит по списку контекстный граф: чем больше слов, тем дороже
 * декодирование и тем слабее эффект на каждое слово. 300 записей — примерно
 * тот объём, где слова ещё различимы, а декодирование не замедляется заметно.
 */
const MAX_ENTRIES = 300;

